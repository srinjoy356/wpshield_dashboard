);

-- Users can read own managed reviews
CREATE POLICY "Users can read own managed reviews" ON public.managed_reviews
FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM user_profiles
    WHERE user_profiles.id = auth.uid()
